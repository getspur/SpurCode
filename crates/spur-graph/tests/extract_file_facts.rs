#[test]
fn errors_propagate_and_do_not_poison_reused_extractor() {
    let path = Path::new("virtual/source.rs");
    let mut extractor = BytesExtractor::for_language(Language::Rust).unwrap();
    assert!(matches!(
        extractor.extract_file_facts(path, &[0xff]),
        Err(ExtractError::InvalidUtf8(_))
    ));
    assert_same_facts(
        &extractor.extract_file_facts(path, RUST.as_bytes()).unwrap(),
        &native_file("virtual/source.rs", RUST.as_bytes()),
    );

    let mut notebook = BytesExtractor::for_language(Language::JupyterNotebook).unwrap();
    for bytes in [b"".as_slice(), b"not a notebook", &[0xff]] {
        assert!(matches!(
            notebook.extract_file_facts(Path::new("virtual/bad.ipynb"), bytes),
            Err(ExtractError::Extraction(_))
        ));
    }
    let bytes = br#"{"cells":[],"metadata":{}}"#;
    assert_same_facts(
        &notebook
            .extract_file_facts(Path::new("virtual/good.ipynb"), bytes)
            .unwrap(),
        &native_file("virtual/good.ipynb", bytes),
    );
}

#[test]
fn logical_path_is_nonempty_relative_and_cannot_escape() {
    let mut extractor = BytesExtractor::for_language(Language::Rust).unwrap();
    for invalid in [
        "",
        ".",
        "./",
        "/virtual/file.rs",
        "../escape.rs",
        "src/../../escape.rs",
        "..\\escape.rs",
        "C:\\virtual\\file.rs",
        "C:relative.rs",
        "./C:\\virtual\\file.rs",
        "\\\\server\\share\\file.rs",
    ] {
        assert!(
            extractor
                .extract_file_facts(Path::new(invalid), b"fn f() {}")
                .is_err(),
            "accepted invalid logical path {invalid:?}"
        );
    }
    let expected = native_file("virtual/雪/source.rs", RUST.as_bytes());
    let actual = extractor
        .extract_file_facts(Path::new("./virtual/雪/./source.rs"), RUST.as_bytes())
        .unwrap();
    assert_same_facts(&actual, &expected);
}

