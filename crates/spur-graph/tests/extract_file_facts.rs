use std::fs;
use std::path::{Path, PathBuf};

use spur_graph::extract::languages::Language;
use spur_graph::extract::tree_sitter::{BytesExtractor, ExtractError};
use spur_graph::{
    build_facts_for_paths, GraphFacts, MacroResolutionEvidence, NodeKind, RelationKind,
};

const RUST: &str = r#"#![allow(dead_code)]
use crate::elsewhere::Remote;
macro_rules! local { () => { helper() }; }
fn helper() {}
#[cfg(test)]
mod tests {
    #[cfg_attr(feature = "extra", test)]
    fn outer() {
        local!();
        wrapper!(panic!("opaque"));
        fn inner() { assert!(true); }
        inner();
        helper();
        remote_call();
    }
}
"#;

// The oracle deliberately uses the pre-existing filesystem API, never the new
// method. Its root is isolated, contains no Git repository, and is gone before
// the bytes API runs. Compare native rows without serialization or projection.
fn native_file(logical_path: &str, bytes: &[u8]) -> GraphFacts {
    let root = tempfile::tempdir().unwrap();
    let path = root.path().join(logical_path);
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, bytes).unwrap();
    build_facts_for_paths(root.path(), &[PathBuf::from(logical_path)]).unwrap()
}

fn assert_same_facts(actual: &GraphFacts, expected: &GraphFacts) {
    assert_eq!(actual.nodes, expected.nodes, "nodes");
    assert_eq!(actual.edges, expected.edges, "edges");
    assert_eq!(actual.spans, expected.spans, "spans");
    assert_eq!(
        actual.macro_invocations, expected.macro_invocations,
        "macro invocations"
    );
    assert_eq!(actual.macro_scopes, expected.macro_scopes, "macro scopes");
}

fn assert_native_parity(logical_path: &str, bytes: &[u8]) -> GraphFacts {
    let expected = native_file(logical_path, bytes);
    let language = Language::from_path(Path::new(logical_path)).unwrap();
    let actual = BytesExtractor::for_language(language)
        .unwrap()
        .extract_file_facts(Path::new(logical_path), bytes)
        .unwrap();
    assert_same_facts(&actual, &expected);
    assert!(actual.nodes.iter().any(|node| node.kind == NodeKind::File));
    assert!(!actual.spans.is_empty());
    actual
}

#[test]
fn rust_matches_native_with_nested_macro_scopes_attributes_and_local_definition() {
    let facts = assert_native_parity("virtual/雪/lib.rs", RUST.as_bytes());
    assert!(!facts.macro_scopes.is_empty());
    let local = facts
        .macro_invocations
        .iter()
        .find(|row| row.normalized_macro_path == "local")
        .unwrap();
    assert!(matches!(
        local.resolution,
        MacroResolutionEvidence::LocalDefinitionCandidate { .. }
    ));
    for raw in [
        "#![allow(dead_code)]",
        "#[cfg(test)]",
        "#[cfg_attr(feature = \"extra\", test)]",
    ] {
        assert!(local.attributes.iter().any(|attr| attr.raw_text == raw));
    }
    assert!(facts
        .macro_invocations
        .iter()
        .any(|row| row.normalized_macro_path == "assert"));
    // A macro's token-tree contents do not become a direct nested invocation.
    assert!(!facts
        .macro_invocations
        .iter()
        .any(|row| row.normalized_macro_path == "panic"));
    assert!(facts
        .edges
        .iter()
        .any(|edge| { edge.relation == RelationKind::Calls && edge.target_node_id.is_some() }));
}

#[test]
fn cpp_matches_native_definitions_imports_calls_and_receiver_evidence() {
    let source = br#"#include "other.hpp"
namespace demo {
struct Worker { int run() { return 1; } };
int helper() { return 2; }
int entry(Worker &worker) { return worker.run() + helper() + external(); }
}
"#;
    let facts = assert_native_parity("virtual/source.cpp", source);
    assert!(facts.nodes.iter().any(|node| node.label == "Worker"));
    assert!(facts
        .edges
        .iter()
        .any(|edge| edge.relation == RelationKind::Calls));
    assert!(facts.macro_invocations.is_empty());
    assert!(facts.macro_scopes.is_empty());
}

#[test]
fn generated_cpp_keeps_native_graph_facts_instead_of_symbol_shortcut() {
    let source = concat!(
        "\n// This file is generated by scripts/inline-data.py, do not edit it manually //\n\n",
        "#include \"unicode/utypes.h\"\n",
        "#include \"unicode/udata.h\"\n",
        "#include \"unicode/uversion.h\"\n\n",
        "extern \"C\" U_EXPORT const unsigned char U_ICUDATA_ENTRY_POINT [] = {\n",
        "0, 1, 255,\n};\n"
    );
    assert_native_parity("virtual/icu.cpp", source.as_bytes());
}

#[test]
fn python_matches_native_classes_imports_and_calls() {
    let source = br#"from remote import remote_call
def helper():
    return 1
class Worker:
    def run(self):
        return helper() + remote_call()
"#;
    let facts = assert_native_parity("virtual/source.py", source);
    assert!(facts.nodes.iter().any(|node| node.kind == NodeKind::Class));
    assert!(facts
        .edges
        .iter()
        .any(|edge| edge.relation == RelationKind::Imports));
}

#[test]
fn markdown_matches_native_sections_and_unresolved_links() {
    let source =
        b"# Overview\n\n[helper](missing.rs)\n\n## Details\n\n[external](https://example.com)\n";
    let facts = assert_native_parity("virtual/readme.md", source);
    assert!(facts
        .nodes
        .iter()
        .any(|node| node.kind == NodeKind::Section));
    assert!(facts
        .edges
        .iter()
        .any(|edge| { edge.relation == RelationKind::Links && edge.target_node_id.is_none() }));
}

#[test]
fn structured_languages_match_native_keys_and_openapi_resources() {
    for (path, source) in [
        ("virtual/settings.json", "{\"service\": {\"enabled\": true}}"),
        ("virtual/settings.yaml", "service:\n  enabled: true\n"),
        ("virtual/settings.toml", "[service]\nenabled = true\n"),
        (
            "virtual/openapi.json",
            r#"{"openapi":"3.0.0","info":{"title":"Demo","version":"1"},"paths":{"/pets":{"get":{"operationId":"listPets","responses":{"200":{"description":"ok"}}}}}}"#,
        ),
        (
            "virtual/openapi.yaml",
            "openapi: 3.0.0\ninfo:\n  title: Demo\n  version: '1'\npaths:\n  /pets:\n    get:\n      operationId: listPets\n      responses:\n        '200':\n          description: ok\n",
        ),
    ] {
        let facts = assert_native_parity(path, source.as_bytes());
        assert!(facts.nodes.iter().any(|node| node.kind != NodeKind::File));
    }
}

#[test]
fn notebook_matches_native_cells_markdown_and_language_overrides() {
    let source = serde_json::json!({
        "nbformat": 4,
        "nbformat_minor": 5,
        "metadata": {"kernelspec": {"name": "python3"}},
        "cells": [
            {"id": "intro", "cell_type": "markdown", "metadata": {},
             "source": ["# Notebook\n", "[link](missing.py)\n"]},
            {"id": "python", "cell_type": "code", "metadata": {},
             "source": ["def helper():\n", "    return 1\n", "helper()\n"]},
            {"id": "rust", "cell_type": "code",
             "metadata": {"spur": {"code_type": "rust"}},
             "source": ["fn rust_cell() { panic!(\"cell\"); }\n"]}
        ]
    });
    let bytes = serde_json::to_vec(&source).unwrap();
    let facts = assert_native_parity("virtual/analysis.ipynb", &bytes);
    for kind in [NodeKind::Cell, NodeKind::Section, NodeKind::Function] {
        assert!(facts.nodes.iter().any(|node| node.kind == kind));
    }
    // Native macro evidence covers physical Rust files, not notebook cells.
    assert!(facts.macro_invocations.is_empty());
    assert!(facts.macro_scopes.is_empty());
}

