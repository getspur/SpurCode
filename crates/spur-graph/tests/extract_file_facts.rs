#[test]
fn repeated_calls_start_fresh_ids_and_do_not_resolve_against_previous_files() {
    let mut extractor = BytesExtractor::for_language(Language::Python).unwrap();
    let definitions = b"def remote_call():\n    return 1\n";
    let calls = b"def caller():\n    return remote_call()\n";
    let first = extractor
        .extract_file_facts(Path::new("virtual/remote.py"), definitions)
        .unwrap();
    let second = extractor
        .extract_file_facts(Path::new("virtual/caller.py"), calls)
        .unwrap();
    assert_same_facts(&first, &native_file("virtual/remote.py", definitions));
    assert_same_facts(&second, &native_file("virtual/caller.py", calls));
    assert!(second.edges.iter().any(|edge| {
        edge.relation == RelationKind::Calls
            && edge.target_label.as_deref() == Some("remote_call")
            && edge.target_node_id.is_none()
    }));
    assert_same_facts(
        &extractor
            .extract_file_facts(Path::new("virtual/remote.py"), definitions)
            .unwrap(),
        &first,
    );
    assert_same_facts(
        &extractor
            .extract_file_facts(Path::new("virtual/caller.py"), calls)
            .unwrap(),
        &second,
    );
}

#[test]
fn reused_rust_extractor_does_not_leak_macro_evidence_or_local_bindings() {
    let mut extractor = BytesExtractor::for_language(Language::Rust).unwrap();
    let first = extractor
        .extract_file_facts(Path::new("virtual/lib.rs"), RUST.as_bytes())
        .unwrap();
    let plain = extractor
        .extract_file_facts(Path::new("virtual/plain.rs"), b"fn plain() {}")
        .unwrap();
    assert_same_facts(&plain, &native_file("virtual/plain.rs", b"fn plain() {}"));
    assert!(plain.macro_invocations.is_empty());
    assert!(plain.macro_scopes.is_empty());
    assert_same_facts(
        &extractor
            .extract_file_facts(Path::new("virtual/lib.rs"), RUST.as_bytes())
            .unwrap(),
        &first,
    );
}
